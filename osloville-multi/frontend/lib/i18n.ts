export function t(key: string, lang: Lang = 'en', variables: Variables = {}): string {
  const template = dictionary[lang][key] ?? dictionary.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(variables[name] ?? `{${name}}`));
}

export function detectLang(): Lang {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('oslo_lang');
    if (saved === 'en' || saved === 'ru') return saved;
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ru')) return 'ru';
  return 'en';
}

export const localeFor = (lang: Lang) => lang === 'ru' ? 'ru-RU' : 'en-GB';
export const languageLabel = (lang: Lang, displayLang: Lang) => t(`language.${lang}`, displayLang);

export function weatherLabel(description: string | undefined, lang: Lang): string {
  const weatherKey: Record<string, string> = {
    'Freezing & clear ❄️': 'weather.freezing',
    'Snowing ❄️': 'weather.snow',
    'Rainy 🌧️': 'weather.rain',
    'Sunny summer ☀️': 'weather.sunny',
    'Golden hour ☀️': 'weather.golden',
  };
  return t(weatherKey[description || ''] || 'weather.unknown', lang);
}
